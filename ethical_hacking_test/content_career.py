def _rotate(q: tuple, shift: int) -> tuple:
    """Move the correct answer to a different letter so the answer key is not always B."""
    question, options, correct, explanation = q
    pos = shift % 4
    rest = [o for i, o in enumerate(options) if i != correct]
    opts = rest[:pos] + [options[correct]] + rest[pos:]
    return question, opts, pos, explanation


